#!/usr/bin/env python3
"""rules-pull — kéo bộ rule code (KU trong knowledgelib) về repo hiện tại.

Nguồn: <KNOWLEDGELIB_HOME>/software/coding-rules/<lang>-code-rules.md
       (frontmatter + dòng **rule_set_version:** + khối ```yaml rules: ...```)
Sinh:  docs/rules/<out>.md   (luật đã render, KHÔNG sửa tay)
       rules.lock            (phiên bản + hash → mỗi lần update có diff thấy được)
Local: rules.local.yaml      (override có lý do; pull không ghi đè file này)
       rules.local.md        (ghi chú riêng của repo nối vào cuối doc; pull không ghi đè)

Usage:
  rules-pull.py --lang js-ts,go [--root .] [--kl PATH] [--diff | --check] [--wire-claude]

  --diff         in thay đổi so với rules.lock, không ghi gì
  --check        exit 1 nếu lock/outputs lệch KU (dùng cho CI); không ghi
  --wire-claude  thêm dòng @docs/rules/<out>.md vào CLAUDE.md nếu chưa có

Exit: 0 ok · 1 --check lệch · 2 lỗi đầu vào (thiếu KU, override thiếu reason, lang lạ...)
"""
import argparse
import hashlib
import json
import os
import re
import sys

import yaml

OUT_NAME = {"js-ts": "js", "go": "go"}      # lang KU -> tên file docs/rules/<out>.md
LANG_TITLE = {"js-ts": "JavaScript / TypeScript", "go": "Go"}
SEV_ORDER = {"error": 0, "warn": 1}


class Fail(Exception):
    pass


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def kl_home(arg):
    return os.path.expanduser(arg or os.environ.get("KNOWLEDGELIB_HOME") or "~/Documents/Repo/knowledgelib_data")


def load_ku(kl, lang):
    if lang not in OUT_NAME:
        raise Fail(f"lang lạ: {lang} (hỗ trợ: {', '.join(sorted(OUT_NAME))})")
    rel = f"software/coding-rules/{lang}-code-rules.md"
    path = os.path.join(kl, rel)
    if not os.path.isfile(path):
        raise Fail(f"không thấy KU: {path}")
    text = open(path, encoding="utf-8").read()
    mv = re.search(r"\*\*rule_set_version:\*\*\s*`([^`]+)`", text)
    if not mv:
        raise Fail(f"{rel}: thiếu dòng **rule_set_version:** `x.y.z`")
    block = None
    for m in re.finditer(r"```yaml\n(.*?)```", text, re.S):
        if re.search(r"^rules:\s*$", m.group(1), re.M):
            block = m.group(1)
            break
    if block is None:
        raise Fail(f"{rel}: thiếu khối ```yaml rules:```")
    try:
        rules = (yaml.safe_load(block) or {}).get("rules") or []
    except yaml.YAMLError as e:
        raise Fail(f"{rel}: YAML lỗi: {e}")
    seen = set()
    for r in rules:
        for k in ("id", "severity", "kind", "statement"):
            if not r.get(k):
                raise Fail(f"{rel}: rule thiếu trường '{k}': {r.get('id', r)}")
        if r["id"] in seen:
            raise Fail(f"{rel}: id trùng: {r['id']}")
        seen.add(r["id"])
    return {"lang": lang, "version": mv.group(1), "source": rel, "sha": sha(text), "rules": rules}


def load_local_notes(root):
    path = os.path.join(root, "rules.local.md")
    if not os.path.isfile(path):
        return None, None
    text = open(path, encoding="utf-8").read()
    return text, sha(text)


def load_overrides(root):
    path = os.path.join(root, "rules.local.yaml")
    if not os.path.isfile(path):
        return {}
    try:
        data = yaml.safe_load(open(path, encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        raise Fail(f"rules.local.yaml YAML lỗi: {e}")
    out = {}
    for o in data.get("overrides") or []:
        if not o.get("id"):
            raise Fail("rules.local.yaml: override thiếu id")
        if not str(o.get("reason", "")).strip():
            raise Fail(f"rules.local.yaml: override {o['id']} thiếu reason (bắt buộc có lý do)")
        if o.get("action") not in ("disable", "severity"):
            raise Fail(f"rules.local.yaml: override {o['id']} action phải là disable|severity")
        if o["action"] == "severity" and o.get("severity") not in SEV_ORDER:
            raise Fail(f"rules.local.yaml: override {o['id']} severity phải là error|warn")
        out[o["id"]] = o
    return out


def apply_overrides(rules, overrides):
    applied, result = [], []
    for r in rules:
        o = overrides.get(r["id"])
        if not o:
            result.append(r)
        elif o["action"] == "disable":
            applied.append((r["id"], "tắt", o["reason"]))
        else:
            result.append({**r, "severity": o["severity"]})
            applied.append((r["id"], f"severity → {o['severity']}", o["reason"]))
    return result, applied


def render(ku, rules, applied, local_notes=None):
    title = LANG_TITLE[ku["lang"]]
    lines = [
        f"<!-- GENERATED by rules-pull từ {ku['source']} (rule_set_version {ku['version']}, sha {ku['sha']}) -->",
        "<!-- Đừng sửa tay: sửa KU trong knowledgelib hoặc override ở rules.local.yaml, rồi chạy lại rules-pull -->",
        "",
        f"# {title} — rule code (v{ku['version']})",
        "",
        "`error` = chặn; `warn` = đếm ratchet. `machine` = lint kiểm được; `review` = soát tay; `refactor` = kinh nghiệm cấu trúc.",
        "",
    ]
    groups = {}
    for r in rules:
        parts = r["id"].split("-")
        groups.setdefault(parts[1] if len(parts) > 2 else "MISC", []).append(r)
    for g, rs in groups.items():
        lines += [f"## {g}", ""]
        for r in sorted(rs, key=lambda x: (SEV_ORDER.get(x["severity"], 9), x["id"])):
            scope = ",".join(r.get("scope") or [])
            lines.append(f"- **{r['id']}** [{r['severity']}/{r['kind']}] {r['statement']}")
            meta = []
            if r.get("check"):
                meta.append(f"check: `{r['check']}`")
            if scope:
                meta.append(f"scope: {scope}")
            if r.get("evidence"):
                meta.append(f"bằng chứng: {r['evidence']}")
            if meta:
                lines.append("  - " + " · ".join(meta))
        lines.append("")
    if applied:
        lines += ["## Override cục bộ (rules.local.yaml)", ""]
        lines += [f"- **{i}**: {what} — {why}" for i, what, why in applied]
        lines.append("")
    if local_notes is not None:
        lines += ["## Ghi chú riêng của repo (rules.local.md)", ""]
        lines.append(local_notes.rstrip("\r\n"))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def rule_hashes(rules):
    return {r["id"]: sha(json.dumps(r, sort_keys=True, ensure_ascii=False)) for r in rules}


def diff_sets(old, new):
    """old/new = entry trong lock (version, rules{id:hash}) hoặc None."""
    if old is None:
        return [f"  + bộ mới, {len(new['rules'])} rule"]
    out = []
    if old["version"] != new["version"]:
        out.append(f"  version {old['version']} → {new['version']}")
    o, n = old["rules"], new["rules"]
    out += [f"  + {i}" for i in sorted(set(n) - set(o))]
    out += [f"  - {i}" for i in sorted(set(o) - set(n))]
    out += [f"  ~ {i}" for i in sorted(i for i in set(o) & set(n) if o[i] != n[i])]
    if old.get("local_notes_sha") != new.get("local_notes_sha"):
        out.append("  ~ rules.local.md")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lang", required=True)
    ap.add_argument("--root", default=".")
    ap.add_argument("--kl")
    ap.add_argument("--diff", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--wire-claude", action="store_true")
    a = ap.parse_args()
    root, kl = os.path.abspath(a.root), kl_home(a.kl)
    lock_path = os.path.join(root, "rules.lock")
    lock = {"schema": 1, "sets": {}}
    if os.path.isfile(lock_path):
        try:
            lock = json.load(open(lock_path, encoding="utf-8"))
        except json.JSONDecodeError:
            raise Fail("rules.lock hỏng (không phải JSON)")
    overrides = load_overrides(root)
    local_notes, local_notes_sha = load_local_notes(root)
    dirty, new_lock = False, {"schema": 1, "sets": dict(lock.get("sets", {}))}
    writes = []
    for lang in [x.strip() for x in a.lang.split(",") if x.strip()]:
        ku = load_ku(kl, lang)
        rules, applied = apply_overrides(ku["rules"], overrides)
        doc = render(ku, rules, applied, local_notes=local_notes)
        out_rel = f"docs/rules/{OUT_NAME[lang]}.md"
        entry = {"version": ku["version"], "source": ku["source"], "sha": ku["sha"],
                 "rules": rule_hashes(ku["rules"]), "output": out_rel, "output_sha": sha(doc),
                 "overrides": sorted(overrides), "local_notes_sha": local_notes_sha}
        old = lock.get("sets", {}).get(lang)
        changes = diff_sets(old, entry)
        out_path = os.path.join(root, out_rel)
        on_disk = open(out_path, encoding="utf-8").read() if os.path.isfile(out_path) else None
        stale = (old is None or old.get("sha") != ku["sha"] or on_disk != doc
                 or old.get("overrides") != entry["overrides"]
                 or old.get("local_notes_sha") != entry["local_notes_sha"])
        print(f"[{lang}] v{ku['version']} · {len(rules)} rule dùng ({len(ku['rules'])} trong KU) · "
              f"{'LỆCH' if stale else 'khớp'}")
        for c in changes:
            print(c)
        if stale and not changes:
            print("  (nội dung/override đổi, id + version giữ nguyên)")
        dirty |= stale
        new_lock["sets"][lang] = entry
        writes.append((out_path, doc))
    if a.check:
        return 1 if dirty else 0
    if a.diff:
        return 0
    for path, doc in writes:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8").write(doc)
    open(lock_path, "w", encoding="utf-8").write(json.dumps(new_lock, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    print(f"ghi {len(writes)} file docs/rules + rules.lock")
    if a.wire_claude:
        cm = os.path.join(root, "CLAUDE.md")
        if not os.path.isfile(cm):
            print("bỏ qua --wire-claude: không có CLAUDE.md")
        else:
            text = open(cm, encoding="utf-8").read()
            add = [f"@docs/rules/{OUT_NAME[l.strip()]}.md" for l in a.lang.split(",")
                   if f"@docs/rules/{OUT_NAME[l.strip()]}.md" not in text]
            if add:
                open(cm, "w", encoding="utf-8").write(text.rstrip("\n") + "\n\n" + "\n".join(add) + "\n")
                print("CLAUDE.md +", ", ".join(add))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Fail as e:
        print(f"rules-pull: {e}", file=sys.stderr)
        sys.exit(2)
